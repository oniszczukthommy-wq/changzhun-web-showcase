// Explicitly exposed native commands; request authentication lives in web.rs.
use serde_json::Value;
use tauri::Manager;
fn arg<T: serde::de::DeserializeOwned>(args: &Value, key: &str) -> Result<T, String> {
    serde_json::from_value(args.get(key).cloned().unwrap_or(Value::Null)).map_err(|e| format!("参数 {key} 无效：{e}"))
}
fn value<T: serde::Serialize>(v: T) -> Result<Value, String> { serde_json::to_value(v).map_err(|e| e.to_string()) }
pub fn dispatch(app: &tauri::AppHandle, command: &str, args: Value) -> Result<Value, String> {
    match command {
        "qqmusic_open" => value(crate::qqmusic_open(arg::<Option<String>>(&args,"target")?)?),
        "qqmusic_status" => value(crate::qqmusic_status()),
        "set_qqmusic_browser" => value(crate::set_qqmusic_browser(arg::<String>(&args,"browser")?)?),
        "player_control" => value(crate::player_control(arg::<String>(&args, "action")?)),
        "play_track" => value(crate::play_track(arg::<String>(&args, "id")?, app.get_webview_window("main").ok_or("辅助程序窗口未就绪")?, app.state())),
        "open_in_app" => value(crate::open_in_app(arg::<String>(&args, "id")?, app.state())),
        "open_app" => value(crate::open_app(arg::<String>(&args, "id")?, app.state())),
        "allow_control" => value(crate::allow_control(arg::<String>(&args, "key")?)),
        "rename_track" => value(crate::rename_track(arg::<String>(&args, "id")?, arg::<String>(&args, "artist")?, arg::<String>(&args, "name")?)?),
        "set_blind" => value(crate::set_blind(arg::<bool>(&args, "on")?, app.state())),
        "play_along" => value(crate::play_along(arg::<String>(&args, "track")?, arg::<f64>(&args, "position")?, app.state(), app.state(), app.get_webview_window("main").ok_or("辅助程序窗口未就绪")?)),
        "along_mode" => value(crate::along_mode(arg::<String>(&args, "track")?, app.state())),
        "join_along" => value(crate::join_along(arg::<String>(&args, "track")?, app.state(), app.state())),
        "stop_play_along" => value(crate::stop_play_along(app.state(), app.state())),
        "take_playing" => value(crate::take_playing(arg::<bool>(&args, "on")?)),
        "player_now" => value(crate::player_now(app.state())),
        "catch_up" => value(crate::catch_up()),
        "finish_take" => value(crate::finish_take(app.state())),
        "set_youtube" => value(crate::set_youtube(arg::<bool>(&args, "on")?)),
        "set_setting" => value(crate::set_setting(arg::<String>(&args, "key")?, arg::<bool>(&args, "on")?)),
        "mics" => value(crate::mics()),
        "set_mic" => value(crate::set_mic(arg::<Option<String>>(&args, "uid")?)),
        "output_timing" => value(crate::output_timing(app.state())),
        "output_timing_check" => value(crate::output_timing_check(arg::<String>(&args, "uid")?, arg::<crate::timing::Run>(&args, "run")?)),
        "output_timing_reset" => value(crate::output_timing_reset(arg::<String>(&args, "uid")?)),
        "output_timing_dismiss" => value(crate::output_timing_dismiss(arg::<String>(&args, "uid")?)),
        "settings_now" => value(crate::settings_now()),
        "set_echo_cancel" => value(crate::set_echo_cancel(arg::<bool>(&args, "on")?, app.state())),
        "skip_to" => value(crate::skip_to(arg::<f64>(&args, "seconds")?, app.state())),
        "delete_take" => value(crate::delete_take(arg::<String>(&args, "id")?, app.state())),
        "forget_song" => value(crate::forget_song(arg::<String>(&args, "id")?, app.state())),
        "stop_learning" => value(crate::stop_learning(arg::<String>(&args, "id")?, arg::<Option<String>>(&args, "name")?, arg::<Option<String>>(&args, "artist")?, app.clone(), app.state(), app.state())),
        "learn_anyway" => value(crate::learn_anyway(arg::<String>(&args, "id")?)),
        "set_favorite" => value(crate::set_favorite(arg::<String>(&args, "id")?, arg::<bool>(&args, "favorite")?, arg::<Option<String>>(&args, "name")?, arg::<Option<String>>(&args, "artist")?, app.state())),
        "is_favorite" => value(crate::is_favorite(arg::<String>(&args, "id")?, arg::<Option<String>>(&args, "name")?, arg::<Option<String>>(&args, "artist")?, app.state())),
        "takes" => value(crate::takes(app.state())),
        "library" => value(crate::library(app.state())),
        "take" => value(crate::take(arg::<String>(&args, "id")?, app.state())),
        "share_window" => value(crate::share_window(arg::<String>(&args, "id")?, arg::<Option<f64>>(&args, "t")?, app.state())),
        "share_take" => value(crate::share_take(arg::<String>(&args, "id")?, arg::<i64>(&args, "start")?, app.state())?),
        "take_audio" => value(crate::take_audio(arg::<String>(&args, "id")?, app.state())),
        "open_link" => value(crate::open_link(arg::<String>(&args, "url")?)),
        "starter_cover" => value(crate::starter_cover(arg::<String>(&args, "artist")?, arg::<String>(&args, "title")?, app.clone())),
        "third_party_notices" => value(crate::third_party_notices(app.clone())?),
        "perf_frames" => value(crate::perf_frames(arg::<Value>(&args, "report")?)),
        "report_prepare" => value(crate::report_prepare(arg::<Option<String>>(&args, "take")?, app.clone())?),
        "report_save" => value(crate::report_save(arg::<String>(&args, "description")?, app.clone())?),
        "report_open_folder" => value(crate::report_open_folder()),
        "ui_log" => value(crate::ui_log(arg::<String>(&args, "msg")?)),
        "ui_moving" => value(crate::ui_moving(arg::<bool>(&args, "moving")?)),
        "open_privacy_settings" => value(crate::open_privacy_settings()),
        "setup_status" => value(crate::setup_status()),
        "setup_request" => value(crate::setup_request(arg::<String>(&args, "what")?)),
        "setup_open_settings" => value(crate::setup_open_settings(arg::<String>(&args, "what")?)),
        "setup_meter" => value(crate::setup_meter(arg::<bool>(&args, "on")?)),
        "setup_level" => value(crate::setup_level()),
        "setup_control" => value(crate::setup_control(arg::<bool>(&args, "allow")?)),
        "setup_done" => value(crate::setup_done(arg::<bool>(&args, "done")?)),
        "report_show" => value(crate::report_show(arg::<String>(&args, "path")?)),
        "report_issue" => value(crate::report_issue(arg::<Option<String>>(&args, "take")?)),
        "dev_tools" => Ok(Value::Bool(false)),
        "set_mini" => Ok(Value::Null),
        _ => Err("不支持的操作".into()),
    }
}
